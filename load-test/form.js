import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter } from 'k6/metrics';
import { pause, shape, thresholds } from './lib/profile.js';

// The applicant's path: load the Categories, then submit an Application.
//
// BASE_URL decides what is measured. Through the form's nginx
// (http://frontend:8080) the per-address limit answers 429 after ten POSTs;
// set EXPECT_LIMIT=1 to count a 429 as the expected answer there. Against the
// backend directly (http://backend:8080) there is no nginx limit, which is
// what measures how many Applications the backend can write.
const baseUrl = __ENV.BASE_URL || 'http://localhost:8081';
const expectLimit = __ENV.EXPECT_LIMIT === '1';

export const options = {
  ...shape(),
  thresholds: expectLimit ? { checks: ['rate>0.99'] } : thresholds,
};

const accepted = new Counter('applications_accepted');
const limited = new Counter('applications_limited');

const weeklyTimes = ['HOURS_1_2', 'HOURS_3_5', 'HOURS_5_PLUS', 'IRREGULAR'];

export default function () {
  const categories = http.get(`${baseUrl}/api/v1/categories`, {
    tags: { name: 'GET /api/v1/categories' },
  });
  check(categories, { 'categories 200': (r) => r.status === 200 });

  const list = categories.status === 200 ? categories.json('categories') : [];
  if (!list || list.length === 0) {
    sleep(pause);
    return;
  }

  // A new email for every request: the backend accepts three Applications per
  // address in 24 hours (A26). example.org never receives mail, and
  // RESEND_API_KEY stays empty on the load stack anyway.
  const submissionId = crypto.randomUUID();
  const body = {
    submissionId,
    categoryId: list[(__VU + __ITER) % list.length].id,
    name: `Load Test ${__VU}-${__ITER}`,
    email: `load-${submissionId}@example.org`,
    weeklyTime: weeklyTimes[__ITER % weeklyTimes.length],
    about: 'Generated by load-test/form.js.',
    privacyConsent: true,
    consentTextVersion: '2026-09',
    website: '',
  };

  const submitted = http.post(`${baseUrl}/api/v1/applications`, JSON.stringify(body), {
    headers: { 'Content-Type': 'application/json' },
    tags: { name: 'POST /api/v1/applications' },
    responseCallback: expectLimit
      ? http.expectedStatuses(200, 201, 429)
      : http.expectedStatuses(200, 201),
  });

  if (submitted.status === 429) {
    limited.add(1);
  } else if (submitted.status === 200 || submitted.status === 201) {
    accepted.add(1);
  }

  if (expectLimit) {
    check(submitted, { 'accepted or limited': (r) => [200, 201, 429].includes(r.status) });
  } else {
    check(submitted, { 'application accepted': (r) => r.status === 200 || r.status === 201 });
  }

  sleep(pause);
}
